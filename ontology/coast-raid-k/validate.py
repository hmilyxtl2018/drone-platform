def extra_algorithms(data: dict) -> list[str]:
    errs: list[str] = extra_gate_give(data)
    tools = {t["id"]: t for t in data.get("tools") or []}
    fns = {f["id"]: f for f in data.get("functions") or []}
    if not tools:
        errs.append("ToolCatalog.tools missing")
        return errs
    for tid, tool in tools.items():
        if tool.get("claim") is not False:
            errs.append(f"{tid} claim must be false")
        if tool.get("type") != "Algorithm":
            errs.append(f"{tid} type must be Algorithm")
        bind = tool.get("bind")
        if bind not in fns:
            errs.append(f"{tid} bind {bind!r} not a FunctionBind")
        if tid in CLAIM_TOOLS and tool.get("scope") != "tool":
            errs.append(f"{tid} must have scope=tool (not a claim, not inner loop)")
    inner = (data.get("innerLoop") or {}).get("name")
    if inner != "spherical_code":
        errs.append(f"innerLoop.name must be spherical_code, got {inner!r}")
    if inner in CLAIM_TOOLS:
        errs.append("MAPPO/HAPPO/QMIX cannot be innerLoop")
    for fid, fn in fns.items():
        for bid in fn.get("bound") or []:
            if bid not in tools:
                errs.append(f"function {fid} bound {bid} missing from tools")
        for extra in fn.get("toolsNotClaim") or []:
            t = tools.get(extra)
            if not t:
                errs.append(f"{fid} toolsNotClaim {extra} missing")
            elif t.get("claim") is not False:
                errs.append(f"{extra} listed toolsNotClaim but claim is not false")
        if "nMax" in fn:
            errs.append(f"function {fid} must not store nMax; owner is Rule.N_bound")
        if "tau" in fn:
            errs.append(f"function {fid} must not store tau; owner is Rule.gate")
    sm = data.get("stateModel") or {}
    if sm.get("kind") != "compile":
        errs.append("ToolCatalog.stateModel.kind must be compile")
    return errs


def extra_tbox(data: dict) -> list[str]:
    errs: list[str] = []
    classes = {c["id"]: c for c in data.get("classes") or []}
    if "Entity" not in classes:
        errs.append("TBox missing Entity")
    if classes.get("Entity", {}).get("subClassOf"):
        errs.append("Entity must be top (empty subClassOf)")
    for cid, cls in classes.items():
        for parent in cls.get("subClassOf") or []:
            if parent not in classes:
                errs.append(f"{cid} subClassOf unknown {parent}")

    def cyclic(cid: str, stack: list[str]) -> bool:
        if cid in stack:
            return True
        nxt = classes.get(cid, {}).get("subClassOf") or []
        return any(cyclic(p, stack + [cid]) for p in nxt if p in classes)

    for cid in classes:
        if cyclic(cid, []):
            errs.append(f"TBox cycle at {cid}")
            break
    ops = {p["id"]: p for p in data.get("objectProperties") or []}
    hs = ops.get("hasState") or {}
    if hs.get("domain") != "Entity" or hs.get("range") != "Quality":
        errs.append("hasState must be Entity → Quality")
    axioms = {a["id"]: a.get("manchester") or "" for a in data.get("axioms") or []}
    if "hasState some Quality" not in axioms.get("entity-has-quality", ""):
        errs.append("missing axiom Entity SubClassOf hasState some Quality")
    if "claims value false" not in axioms.get("algorithm-no-claim", ""):
        errs.append("missing axiom Algorithm SubClassOf claims value false")
    for a, b in data.get("disjoint") or []:
        if a not in classes or b not in classes:
            errs.append(f"disjoint unknown {a}/{b}")
    for prop in list(data.get("objectProperties") or []) + list(data.get("dataProperties") or []):
        if prop.get("domain") not in classes:
            errs.append(f"{prop.get('id')} domain {prop.get('domain')!r} not a class")
        rng = prop.get("range") or ""
        if rng and not rng.startswith("xsd:") and rng not in classes:
            errs.append(f"{prop.get('id')} range {rng!r} not a class")
    missing = {"Rule", "Algorithm", "Quality", "FunctionBind", "ShellTemplate"} - set(classes)
    if missing:
        errs.append(f"TBox missing {sorted(missing)}")
    return errs


def emit_tbox_ttl(tbox: dict) -> None:
    def iri(name: str) -> str:
        if name.startswith(("xsd:", "owl:", "rdfs:", "rdf:")):
            return name
        if name.startswith(("http://", "https://")):
            return f"<{name}>"
        return f"crk:{name}"

    def esc(text: str) -> str:
        return text.replace("\\", "\\\\").replace('"', '\\"')

    lines = [
        "@prefix owl: <http://www.w3.org/2002/07/owl#> .",
        "@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .",
        "@prefix rdf: <http://www.w3.org/1999/02/22-rdf-syntax-ns#> .",
        "@prefix xsd: <http://www.w3.org/2001/XMLSchema#> .",
        "@prefix crk: <https://local.ontology/coast-raid-k#> .",
        "",
        "crk: a owl:Ontology ;",
        '  rdfs:label "coast-raid-k" ;',
        '  owl:versionInfo "1.0.0" ;',
        '  rdfs:comment "Generated from tbox.json. Not used in the 40ms tick." .',
        "",
    ]
    for cls in tbox.get("classes") or []:
        lines.append(f"{iri(cls['id'])} a owl:Class ;")
        lines.append(f'  rdfs:label "{esc(cls.get("label") or cls["id"])}"@zh ;')
        parents = cls.get("subClassOf") or []
        if parents:
            lines.append("  rdfs:subClassOf " + ", ".join(iri(p) for p in parents) + " ;")
        comment = cls.get("comment")
        if comment:
            lines.append(f'  rdfs:comment "{esc(comment)}"@zh ;')
        for eq in cls.get("equivalentTo") or []:
            lines.append(f"  owl:equivalentClass {iri(eq)} ;")
        for see in cls.get("seeAlso") or []:
            lines.append(f"  rdfs:seeAlso {iri(see)} ;")
        lines[-1] = lines[-1].rstrip(" ;") + " ."
        lines.append("")
    for a, b in tbox.get("disjoint") or []:
        lines.append(f"{iri(a)} owl:disjointWith {iri(b)} .")
    if tbox.get("disjoint"):
        lines.append("")
    for prop in tbox.get("objectProperties") or []:
        lines.append(f"{iri(prop['id'])} a owl:ObjectProperty ;")
        lines.append(f"  rdfs:domain {iri(prop['domain'])} ;")
        lines.append(f"  rdfs:range {iri(prop['range'])} ;")
        if prop.get("inverseOf"):
            lines.append(f"  owl:inverseOf {iri(prop['inverseOf'])} ;")
        if prop.get("comment"):
            lines.append(f'  rdfs:comment "{esc(prop["comment"])}"@zh ;')
        lines[-1] = lines[-1].rstrip(" ;") + " ."
        lines.append("")
    for prop in tbox.get("dataProperties") or []:
        lines.append(f"{iri(prop['id'])} a owl:DatatypeProperty ;")
        lines.append(f"  rdfs:domain {iri(prop['domain'])} ;")
        lines.append(f"  rdfs:range {iri(prop['range'])} ;")
        if prop.get("comment"):
            lines.append(f'  rdfs:comment "{esc(prop["comment"])}"@zh ;')
        lines[-1] = lines[-1].rstrip(" ;") + " ."
        lines.append("")
    lines += [
        "crk:Entity rdfs:subClassOf [",
        "  a owl:Restriction ;",
        "  owl:onProperty crk:hasState ;",
        "  owl:someValuesFrom crk:Quality",
        "] .",
        "",
        "crk:Algorithm rdfs:subClassOf [",
        "  a owl:Restriction ;",
        "  owl:onProperty crk:claims ;",
        "  owl:hasValue \"false\"^^xsd:boolean",
        "] .",
        "",
        "crk:ShellTemplate rdfs:subClassOf [",
        "  a owl:Restriction ;",
        "  owl:onProperty crk:writes ;",
        "  owl:allValuesFrom [ owl:complementOf crk:Permit ]",
        "] .",
        "",
    ]
    for ax in tbox.get("axioms") or []:
        aid = "axiom_" + str(ax["id"]).replace("-", "_")
        lines.append(f"crk:{aid} a owl:Axiom ;")
        lines.append(f'  rdfs:comment "{esc(ax["manchester"])}" .')
        lines.append("")
    dest = ROOT / "tbox.ttl"
    dest.write_text("\n".join(lines), encoding="utf-8")
    print(f"emit ontology/coast-raid-k/tbox.ttl")


def emit_agent_ttl() -> None:
    """Emit the additive Agent TBox so SHACL/OWL tools see the same terms."""
    path = ROOT / "agent.extension.json"
    if not path.exists():
        return
    ext = json.loads(path.read_text(encoding="utf-8"))
    def iri(value: str) -> str:
        if value.startswith(("xsd:", "owl:", "rdfs:", "rdf:")):
            return value
        if value.startswith(("http://", "https://")):
            return f"<{value}>"
        return f"ag:{value}"
    def esc(value: str) -> str:
        return str(value).replace("\\", "\\\\").replace('"', '\\"')
    lines = [
        "@prefix owl: <http://www.w3.org/2002/07/owl#> .",
        "@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .",
        "@prefix ag: <https://local.ontology/coast-raid-k/agent/1.0.0#> .",
        "@prefix crk: <https://local.ontology/coast-raid-k#> .",
        "@prefix xsd: <http://www.w3.org/2001/XMLSchema#> .", "",
        "ag: a owl:Ontology ; rdfs:label \"coast-raid-k Agent extension\"@en ; owl:versionInfo \"1.0.0\" .", "",
    ]
    for cls in ext.get("classes") or []:
        lines.append(f"{iri(cls['iri'])} a owl:Class ;")
        lines.append(f'  rdfs:label "{esc(cls.get("label") or cls["id"])}"@zh ;')
        parents = cls.get("subClassOf") or []
