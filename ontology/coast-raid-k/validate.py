def extra_agent_catalog(data: dict) -> list[str]:
    """Cross-document checks for the Agent instance catalog."""
    errs: list[str] = []
    instances = data.get("instances") or []
    ids = [x.get("id") for x in instances]
    iris = [x.get("iri") for x in instances]
    if len(ids) != len(set(ids)):
        errs.append("agent.instances duplicate id")
    if len(iris) != len(set(iris)):
        errs.append("agent.instances duplicate iri")
    run_id = data.get("runId")
    for item in instances:
        if item.get("runId") != run_id:
            errs.append(f"{item.get('id')} runId must equal catalog runId")
        if item.get("type") != "AgentInstance":
            errs.append(f"{item.get('id')} type must be AgentInstance")
        iri = item.get("iri", "")
        if not iri.startswith("https://local.ontology/coast-raid-k/"):
            errs.append(f"{item.get('id')} iri must use coast-raid-k namespace")
        if item.get("lifecycleState") == "destroyed" and item.get("validTime", {}).get("to") is None:
            errs.append(f"{item.get('id')} destroyed instance must have validTime.to")
    return errs


