def load_schema() -> dict:
    defs: dict = {}
    for name in SCHEMA_MODULES:
        part = json.loads((ROOT / name).read_text(encoding="utf-8"))
        chunk = part.get("$defs") or {}
        clash = set(defs) & set(chunk)
        if clash:
            raise SystemExit(f"duplicate $defs in {name}: {sorted(clash)}")
        defs.update(chunk)
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "https://local.ontology/coast-raid-k/schema.json",
        "title": "coast-raid-k data contract",
        "description": "Merged $defs from schema.*.json (SoR). Do not edit this file by hand.",
        "$defs": defs,
        "oneOf": [{"$ref": f"#/$defs/{n}"} for n in SCHEMA_ONE_OF],
    }


