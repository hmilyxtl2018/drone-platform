def extra_shells(data: dict) -> list[str]:
    errs: list[str] = []
    if data.get("permitWriter") != "monitor.gate":
        errs.append(f"permitWriter must be monitor.gate, got {data.get('permitWriter')!r}")
    theater = json.loads((ROOT / "theater.json").read_text(encoding="utf-8"))
    types = {p["id"]: p for p in theater.get("platformTypes") or []}
    for tmpl in data.get("templates") or []:
        bind = tmpl.get("bindsPlatformType")
        if bind not in types:
            errs.append(f"{tmpl.get('id')} bindsPlatformType {bind!r} not a PlatformType")
        elif types[bind].get("inScene") is not True:
            errs.append(f"{tmpl.get('id')} must not bind catalog type {bind!r}")
        for st in tmpl.get("stages") or []:
            if "Permit" in (st.get("writes") or []):
                errs.append(f"{tmpl.get('id')} stage {st.get('name')} writes Permit")
    return errs


def shore_z(gis: dict, x: float) -> float:
    terms = ((gis.get("shoreline") or {}).get("params") or {}).get("terms") or []
    return sum(t["amp"] * math.sin(x * t["freq"] + t["phase"]) for t in terms)


def in_region(gis: dict, p: list[float], region: str) -> bool:
    sea = p[2] < shore_z(gis, p[0])
    return sea if region == "SEA" else not sea


def sample_body(body: dict) -> list[list[float]]:
    shape = body.get("shape")
    if shape == "aabb":
        pts = []
        for x in (body["x0"], 0.5 * (body["x0"] + body["x1"]), body["x1"]):
            for z in (body["z0"], 0.5 * (body["z0"] + body["z1"]), body["z1"]):
                pts.append([x, body.get("y0", 0), z])
        return pts
    if shape in ("disk", "hemisphere") and body.get("c") is not None:
        c = body["c"]
        r = float(body.get("r") or 0)
        pts = [c[:]]
        for i in range(16):
            a = (2 * math.pi * i) / 16
            pts.append([c[0] + r * math.cos(a), c[1], c[2] + r * math.sin(a)])
        return pts
    if body.get("c"):
        return [body["c"][:]]
    return []


def extra_gis(data: dict) -> list[str]:
    errs: list[str] = []
    if data.get("incomplete"):
        missing = set(data.get("missing") or [])
        need = {"Shoreline", "Region", "Membership"}
        leftover = need - missing
        if leftover:
            errs.append(f"incomplete gis.json must list missing {sorted(leftover)}")
        return errs
    sh = data.get("shoreline") or {}
    if sh.get("kind") == "harmonic":
        terms = (sh.get("params") or {}).get("terms") or []
        if len(terms) < 1:
            errs.append("harmonic shoreline needs params.terms")
        for t in terms:
            if not all(k in t for k in ("amp", "freq", "phase")):
                errs.append(f"term missing amp/freq/phase: {t}")
    theater = json.loads((ROOT / "theater.json").read_text(encoding="utf-8"))
    bodies = {b["id"]: b for b in theater.get("bodies") or []}
    sites = {s["id"]: s for s in theater.get("sites") or []}
    for m in data.get("membership") or []:
        oid, region, rule = m["of"], m["region"], m["rule"]
        if rule == "spans":
            if oid not in bodies and oid not in sites:
                errs.append(f"spans membership of unknown id {oid}")
            continue
        if oid in sites:
            p = sites[oid]["p"]
            if not in_region(data, p, region):
                errs.append(f"membership {oid} {rule} {region} fails at {p}")
            continue
        if oid not in bodies:
            errs.append(f"membership of unknown id {oid}")
            continue
        pts = sample_body(bodies[oid])
        if rule == "in":
            pts = pts[:1]
        for p in pts:
            if not in_region(data, p, region):
                errs.append(f"membership {oid} {rule} {region} fails at {p}")
                break
    mem_of = {m["of"] for m in data.get("membership") or []}
    missing_bodies = sorted(set(bodies) - mem_of)
    if missing_bodies:
        errs.append(f"bodies missing membership (in|subset|spans): {missing_bodies}")
    return errs


def emit_scene_gis(gis: dict) -> None:
    if gis.get("incomplete"):
        return
    dest = ROOT.parents[1] / "demo" / "scene-gis.js"
    payload = json.dumps(gis, ensure_ascii=False, indent=2)
    dest.write_text(
        "/** Generated from ontology/coast-raid-k/gis.json. Do not edit. */\n"
        f"export const GIS = {payload};\n\n"
        "export function shoreZ(x) {\n"
        "  const terms = GIS.shoreline.params.terms;\n"
        "  let z = 0;\n"
        "  for (const t of terms) z += t.amp * Math.sin(x * t.freq + t.phase);\n"
        "  return z;\n"
        "}\n\n"
        "export function inSea(p) {\n"
        "  return p[2] < shoreZ(p[0]);\n"
        "}\n\n"
        "export function inLand(p) {\n"
        "  return p[2] >= shoreZ(p[0]);\n"
        "}\n\n"
        "export function regionOf(p) {\n"
        "  return inSea(p) ? \"SEA\" : \"LAND\";\n"
        "}\n",
        encoding="utf-8",
    )
    print(f"emit {dest.relative_to(ROOT.parents[1])}")


def emit_inventory(*, write: bool = True) -> dict:
    def load(name: str) -> dict:
        return json.loads((ROOT / name).read_text(encoding="utf-8"))

    entries: list[dict] = []

    def add(eid: str, typ: str, module: str, file: str, label: str = "") -> None:
        rec = {"id": eid, "type": typ, "module": module, "file": file}
        if label:
            rec["label"] = label
        entries.append(rec)

    cat = load("catalog.json")
    add(cat["id"], "Package", "领域本体", "catalog.json", cat.get("title", ""))
    for ex in cat.get("excludes") or []:
        add(ex, "Exclude", "战场", "catalog.json")
    tb = load("tbox.json")
    for c in tb.get("classes") or []:
        add(c["id"], "Class", "领域本体", "tbox.json", c.get("label") or "")
    gis = load("gis.json")
    sh = gis.get("shoreline") or {}
    if sh.get("id"):
        add(sh["id"], "Shoreline", "战场", "gis.json")
    for r in gis.get("regions") or []:
        add(r["id"], "Region", "战场", "gis.json", r.get("predicate", ""))
    for m in gis.get("membership") or []:
        add(f"{m['of']}∈{m['region']}", "Membership", "战场", "gis.json", m["rule"])
    th = load("theater.json")
    for b in th.get("bodies") or []:
        add(b["id"], b["type"], "战场", "theater.json", b.get("label", ""))
    for s in th.get("sites") or []:
        add(s["id"], s["type"], "战场", "theater.json", s.get("label", ""))
    for p in th.get("platformTypes") or []:
        add(p["id"], "PlatformType", "战场", "theater.json", p.get("klass") or p.get("side", ""))
    gr = load("graph.json")
    tdl = gr.get("shoreTdl") or {}
    if tdl.get("id"):
        add(tdl["id"], "Needline", "战场", "graph.json", tdl.get("label", ""))
    for lk in gr.get("otherLinks") or []:
        add(lk["id"], "Link", "战场", "graph.json", lk.get("label", ""))
    cs = load("constraints.json")
    ru = load("rules.json")
    for rule in ru.get("rules") or []:
        add(rule["id"], "Rule", "规则", "rules.json", (rule.get("text") or "")[:40])
    for cid, cloud in (cs.get("clouds") or {}).items():
        add(cid, "CloudDef", "知识", "constraints.json", f"Ex {cloud.get('Ex')}")
    shc = load("shells.json")
    add(shc.get("permitWriter", "monitor.gate"), "Monitor", "Agent", "shells.json", "Permit writer")
    for tmpl in shc.get("templates") or []:
        add(tmpl["id"], "ShellTemplate", "Agent", "shells.json", tmpl.get("bindsPlatformType", ""))
    al = load("algorithms.json")
    for tool in al.get("tools") or []:
        add(tool["id"], "Algorithm", "算法", "algorithms.json", tool.get("title") or "")
    for fn in al.get("functions") or []:
        add(fn["id"], "FunctionBind", "交战", "algorithms.json", fn.get("give", ""))
    # Agent instance catalog is an additive extension to the core package.
    # Keep its stable identifiers in the same navigation index used by the UI.
    agent_catalog = load("agent.instances.json")
    for inst in agent_catalog.get("instances") or []:
        add(inst["id"], inst.get("type", "AgentInstance"), "Agent", "agent.instances.json", inst.get("modelId", ""))
    inv = {"package": "coast-raid-k", "generated": True, "entries": entries}
    if write:
        path = ROOT / "inventory.json"
        path.write_text(json.dumps(inv, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print(f"emit ontology/coast-raid-k/inventory.json ({len(entries)} entries)")
    return inv


