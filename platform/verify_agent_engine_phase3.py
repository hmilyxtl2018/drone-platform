"""Rebuild a unique empty DB, apply Phase 3 migrations, and verify contracts.

Only the database generated by this process is dropped. No paid services and
no writes to the ontology source occur. The existing Phase 2 bootstrap is the
base; Phase 3 migrations and explicit configuration are independently applied.
"""
from __future__ import annotations

import argparse
import asyncio
from contextlib import closing
import json
import os
from pathlib import Path
import secrets
import subprocess
import time

import psycopg2
from psycopg2 import sql

from agent_engine.bootstrap import build_engine
from agent_engine.postgres import connection_factory
from agent_tools.fixtures import X200_CAPABILITY_INPUT
from configure_agent_engine_phase3 import configure
from migrate_agent_engine import migrate


ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", default="docs/verification/phase3/bootstrap.json")
    parser.add_argument("--phase4-foundation", action="store_true",
                        help="also verify reviewed Phase 4 migrations in dependency order")
    args = parser.parse_args()
    database = "agent_engine_verify_" + secrets.token_hex(8)
    config = json.loads((ROOT / "db.local.json").read_text(encoding="utf-8"))
    environment = os.environ.copy()
    environment["PGPASSWORD"] = config.get("password", "")
    connection_args = ["-h", str(config.get("host", "127.0.0.1")), "-p", str(config.get("port", 5432)),
                       "-U", config["user"], "-d", database]
    report = {"database": database, "passed": False, "paidCalls": 0}
    created = False
    try:
        with closing(psycopg2.connect(**{**config, "dbname": "postgres"})) as con:
            con.autocommit = True
            with con.cursor() as cursor:
                cursor.execute(sql.SQL("CREATE DATABASE {}").format(sql.Identifier(database)))
                created = True
        result = subprocess.run([r"C:\Program Files\PostgreSQL\17\bin\psql.exe", *connection_args,
                                 "--no-psqlrc", "--set", "ON_ERROR_STOP=1", "-f",
                                 str(ROOT / "db/ontology-agent-admin-postgres.sql")],
                                env=environment, capture_output=True)
        if result.returncode:
            raise RuntimeError("phase2-bootstrap-restore-failed")
        # Keep the Phase 3 baseline limited to 032-039.  Phase 4 migrations
        # have dependencies on the identity tables and must be applied in
        # their explicit numbered order; a filename substring filter would
        # otherwise run 043/044 before 040 and omit 041 entirely.
        paths = sorted(p.relative_to(ROOT).as_posix() for p in (ROOT / "platform/migrations").glob("*_postgres.sql")
                       if p.name[:3].isdigit() and 32 <= int(p.name[:3]) <= 39
                       and "agent_engine" in p.name)
        # The runtime Profile loader requires the DAG dependency column added
        # by the admin publication foundation; apply its two additive
        # migrations even for the Phase 3 smoke database.
        paths.extend([
            'platform/migrations/040_agent_admin_identity_management_postgres.sql',
            'platform/migrations/041_agent_admin_config_publication_postgres.sql',
        ])
        if args.phase4_foundation:
            paths.extend([
                'platform/migrations/042_agent_workbench_workspace_postgres.sql',
                'platform/migrations/043_agent_engine_engineering_tools_postgres.sql',
                'platform/migrations/044_agent_engine_knowledge_publication_postgres.sql',
                'platform/migrations/045_agent_engine_traceability_postgres.sql',
                'platform/migrations/046_agent_engine_evaluation_postgres.sql',
                'platform/migrations/047_agent_engine_operations_postgres.sql',
                'platform/migrations/048_agent_engine_restore_function_path_postgres.sql',
                'platform/migrations/049_agent_engine_manual_calculation_postgres.sql',
                'platform/migrations/050_future_battlefield_analyst_postgres.sql',
                'platform/migrations/051_future_battlefield_tools_and_actions_postgres.sql',
                'platform/migrations/052_future_battlefield_contracts_postgres.sql',
            ])
        report["migrations"] = migrate(paths, database=database, repeats=2)
        report["configuration"] = configure(database)
        # Harness authority is applied after the reviewed Profile configuration
        # so grants and node budgets are generated from the final bindings.
        report["harnessMigration"] = migrate(
            ['platform/migrations/053_agent_harness_contract_postgres.sql'],
            database=database, repeats=2)
        report["baselineMigration"] = migrate(
            ['platform/migrations/054_agent_execution_baseline_postgres.sql'],
            database=database, repeats=2)
        report["contextMigration"] = migrate(
            ['platform/migrations/055_agent_context_collaboration_postgres.sql',
             'platform/migrations/059_agent_handoff_projection_postgres.sql',
             'platform/migrations/060_agent_context_hash_chain_postgres.sql',
             'platform/migrations/065_uav_agent_execution_steps_postgres.sql'],
            database=database, repeats=2)
        from register_execution_baselines import register as register_baselines
        report["baselines"] = register_baselines(database)
        engine = build_engine(database=database)
        run_id = engine.create_run("uav-capability-analyst", X200_CAPABILITY_INPUT)
        result = asyncio.run(engine.execute(run_id))
        assert result["status"] == "completed", "phase2-regression-failed"
        report["fixedRegression"] = {"runId": run_id, "status": result["status"],
                                     "toolCalls": len(engine.repo.list_tool_calls(run_id))}
        research_id = engine.create_run("uav-capability-analyst", {
            "executionMode": "research", "entityId": "equipment-ff2d751e27858b020dd2"})
        frozen = engine.loader.load_for_run(research_id)
        assert frozen.model_policy["providerSnapshot"]["credential_ref"] == "env:DEEPSEEK_API_KEY"
        assert frozen.source_policy["ontologySource"]["read_only"] is True
        assert engine.repo.get_budget(research_id)["limits"]["model_calls"] == 24
        report["researchConfiguration"] = {"runId": research_id, "model": frozen.model_policy["model_name"],
                                            "sourceReadOnly": True, "budgetFrozen": True}
        if args.phase4_foundation:
            from agent_admin.credentials import AdminAuth
            from agent_admin.identity_management import IdentityManagementService
            from agent_workbench.workspaces import WorkspaceRepository
            factory = connection_factory(database=database)
            auth = AdminAuth(factory)
            issued = auth.issue_token('Isolated bootstrap test administrator', ['admin'], 1)
            actor = auth.authenticate(issued['token'])
            identities = IdentityManagementService(factory).list_identities(actor, actor_token=issued['token'])
            assert len(identities) == 1 and identities[0]['operableAdmin']
            workspaces = WorkspaceRepository(factory)
            workspace = workspaces.create(actor, {'title': 'Isolated bootstrap test',
                'question': 'Does the requirement have sufficient evidence?',
                'entityId': 'equipment-ff2d751e27858b020dd2',
                'requirements': {'payloadKg': {'value': 20, 'unit': 'kg', 'operator': '>='}},
                'materials': [{'title': 'Test context', 'text': 'Unverified fixture input.'}]},
                actor_token=issued['token'])
            restored = workspaces.get(actor, workspace['workspaceId'], actor_token=issued['token'])
            assert restored['revision']['content_hash'] == workspace['contentHash']
            report['phase4Foundation'] = {'identityMetadata': True, 'workspaceHashRestored': True,
                'scope': 'empty database rebuild through migration 049; identity/workspace service persistence only; browser workbench and run admission verified separately'}
        report["passed"] = True
    finally:
        if created:
            with closing(psycopg2.connect(**{**config, "dbname": "postgres"})) as con:
                con.autocommit = True
                with con.cursor() as cursor:
                    cursor.execute(sql.SQL("DROP DATABASE {}").format(sql.Identifier(database)))
            report["temporaryDatabaseDropped"] = True
        path = ROOT / args.output
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(report, indent=2, ensure_ascii=False, default=str), encoding="utf-8")
    print(json.dumps(report, ensure_ascii=True, indent=2, default=str))


if __name__ == "__main__":
    main()
